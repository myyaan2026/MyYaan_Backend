UPDATE service_types SET
    service_description = CASE service_code
        WHEN 'BIKE_SERVICE' THEN 'Regular maintenance and repair for bikes'
        WHEN 'CAR_SERVICE' THEN 'Regular maintenance and repair for cars'
        WHEN 'BIKE_WASHING' THEN 'Professional washing for bikes'
        WHEN 'CAR_WASHING' THEN 'Professional washing for cars'
        ELSE service_description
    END,
    is_home_enabled = TRUE,
    home_display_order = CASE service_code
        WHEN 'BIKE_SERVICE' THEN 1 WHEN 'CAR_SERVICE' THEN 2
        WHEN 'BIKE_WASHING' THEN 3 WHEN 'CAR_WASHING' THEN 4
        WHEN 'RUNNING_REPAIR' THEN 5 WHEN 'PUNCTURE' THEN 6
        ELSE home_display_order
    END
WHERE service_code IN ('BIKE_SERVICE', 'CAR_SERVICE', 'BIKE_WASHING', 'CAR_WASHING', 'RUNNING_REPAIR', 'PUNCTURE');

-- Service options describe the required work. Delivery modes remain in
-- service_sub_types, so either dimension can grow independently.
CREATE TABLE IF NOT EXISTS service_options (
    service_option_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id INTEGER NOT NULL REFERENCES service_types(service_id) ON DELETE CASCADE,
    service_option_code VARCHAR(80) NOT NULL,
    service_option_name VARCHAR(150) NOT NULL,
    service_option_description TEXT,
    is_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    is_default BOOLEAN NOT NULL DEFAULT FALSE,
    display_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT service_options_service_code_key UNIQUE (service_id, service_option_code)
);
CREATE UNIQUE INDEX IF NOT EXISTS service_options_one_default_per_service_key
    ON service_options (service_id) WHERE is_default = TRUE;
CREATE INDEX IF NOT EXISTS service_options_service_id_idx
    ON service_options (service_id, is_enabled, display_order);

