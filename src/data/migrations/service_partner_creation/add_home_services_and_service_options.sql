-- Home-screen visibility and descriptions belong to the top-level service.
ALTER TABLE service_types ADD COLUMN IF NOT EXISTS service_description TEXT;
ALTER TABLE service_types ADD COLUMN IF NOT EXISTS is_home_enabled BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE service_types ADD COLUMN IF NOT EXISTS home_display_order INTEGER;

-- Repair and puncture apply to either a bike or a car; existing services
-- retain their BIKE/CAR category.
ALTER TABLE service_types DROP CONSTRAINT IF EXISTS service_types_vehicle_category_check;
ALTER TABLE service_types ADD CONSTRAINT service_types_vehicle_category_check
    CHECK (vehicle_category IN ('BIKE', 'CAR', 'ANY'));

